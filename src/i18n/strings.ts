/** Picks the closest shipped language for a browser locale list. */
export function detectLang(preferred: readonly string[]): Lang {
  for (const tag of preferred) {
    const t = tag.toLowerCase();
    if (t.startsWith('pt')) return 'pt-BR';
    for (const l of LANGS) if (t === l.toLowerCase() || t.startsWith(l.split('-')[0]! + '-') || t === l.split('-')[0]) return l;
  }
  return 'en';
}

export function format(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Russian UI reads Cyrillic names, everyone else the Latin spelling. */
export const usesCyrillic = (lang: Lang): boolean => lang === 'ru';
